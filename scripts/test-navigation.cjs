'use strict';
// The home, the tiles and their sheets: pointer, Back and a tap.
// Run with playwright installed, or set PLAYWRIGHT_MODULE to its path.
const fs = require('node:fs'), path = require('node:path'), http = require('node:http');
const { chromium, devices } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..');
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.jpg': 'image/jpeg', '.png': 'image/png', '.svg': 'image/svg+xml', '.webp': 'image/webp', '.woff2': 'font/woff2' };
const server = http.createServer((req, res) => { const p = decodeURIComponent(new URL(req.url, 'http://x').pathname); const f = path.resolve(root, '.' + (p === '/' ? '/index.html' : p)); if (!fs.existsSync(f) || !fs.statSync(f).isFile()) return res.writeHead(404).end(); res.writeHead(200, { 'Content-Type': types[path.extname(f)] || 'application/octet-stream' }).end(fs.readFileSync(f)); });
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS' : 'FAIL') + ': ' + m); if (!c) fails++; };
(async () => {
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  const o = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || undefined });
  const errs = [];
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const p = await ctx.newPage(); p.on('pageerror', e => errs.push(e.message));
  await p.goto(o + '/index.html'); await p.waitForTimeout(1000);
  await p.click('.door[href="cod.html"]'); await p.waitForURL('**/cod.html', { timeout: 5000 }); await p.waitForTimeout(1500);
  ok(await p.evaluate(() => document.querySelectorAll('#cast .tile').length === 15), 'home → the tiles');
  const open = id => p.evaluate(() => document.getElementById('sheet').hidden).then(hidden => !hidden && id);
  await p.click('.tile[href="#ghost"]'); await p.waitForTimeout(1500);
  ok(await p.evaluate(() => !document.getElementById('sheet').hidden && document.querySelector('.sheet-pic img').getAttribute('src') === document.querySelector('.tile[href="#ghost"] img').getAttribute('src')), 'a tile opens its sheet with the same picture');
  ok(await p.evaluate(() => getComputedStyle(document.getElementById('main')).visibility === 'hidden'), 'the page behind is not drawn');
  await p.click('.sheet-close'); await p.waitForTimeout(1300);
  ok(await p.evaluate(() => document.getElementById('sheet').hidden && !location.hash), 'the back button closes the sheet');
  await p.click('.tile[href="#cutscenes"]'); await p.waitForTimeout(1500);
  await p.click('#tab-mw2'); await p.click('#mw2Missions .mw4-mission-cover'); await p.waitForTimeout(400);
  await p.click('#mw2Detail input[value="2K"] + span'); await p.waitForTimeout(200);
  await p.click('.sheet-close'); await p.waitForTimeout(1300);
  ok(await p.evaluate(() => document.getElementById('sheet').hidden), 'the back button works after choosing a scene and a quality');
  await p.click('.tile[href="#cutscenes"]'); await p.waitForTimeout(1500);
  await p.goBack(); await p.waitForTimeout(1300);
  ok(await p.evaluate(() => document.getElementById('sheet').hidden), 'browser Back closes the sheet');
  ok(await p.evaluate(() => { document.querySelector('.tile.is-locked').click(); return document.getElementById('sheet').hidden; }), 'a locked tile does nothing');
  const ph = await browser.newContext(devices['iPhone 13']);
  const q = await ph.newPage(); q.on('pageerror', e => errs.push(e.message));
  await q.goto(o + '/cod.html'); await q.waitForTimeout(1500);
  await q.tap('.tile[href="#gaz"]'); await q.waitForTimeout(1500);
  ok(await q.evaluate(() => location.hash === '#gaz' && !document.getElementById('sheet').hidden), 'phone: tap opens Gaz');
  ok(errs.length === 0, 'no page errors ' + JSON.stringify(errs));
  await browser.close(); server.close();
  console.log(fails ? fails + ' failed' : 'all passed');
  process.exitCode = fails ? 1 : 0;
})();
